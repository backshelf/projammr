const run = promisify(execFile);

const HEADER =
  "// generated by apps/server/scripts/generate-api.ts — do not edit by hand";

/**
 * openapi-typescript renders through the TypeScript compiler's AST factory,
 * which the 7.x `typescript` package no longer exposes. Running it under
 * `bunx` gives it its own 5.x resolution and leaves the server on 7.
 */
const OPENAPI_TYPESCRIPT = "openapi-typescript@7.13.0";

const API_SRC = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../../packages/api/src"
);

/**
 * Every value list `packages/api` mirrors, paired with the type alias its
 * consumers import. Adding one is a single entry here: the values must come
 * from the module that owns them — a `raw*` export of the schema,
 * `lib/media.ts` for the audio extensions, or the settings registry for a
 * setting's options — never a literal repeated below.
 */
const ENUMS: { name: string; type: string; values: readonly string[] }[] = [
  { name: "MEMBER_ROLES", type: "MemberRole", values: rawMemberRoleEnum },
  {
    name: "INSTANCE_ROLES",
    type: "InstanceRole",
    values: rawInstanceRoleEnum,
  },
  {
    name: "REGISTRATION_MODES",
    type: "RegistrationMode",
    values: REGISTRATION_MODES,
  },
  { name: "ENTITY_KINDS", type: "EntityKind", values: rawEntityKindEnum },
  {
    name: "COMMENT_TARGETS",
    type: "CommentTarget",
    values: rawCommentTargetEnum,
  },
  { name: "LABEL_TARGETS", type: "LabelTarget", values: rawLabelTargetEnum },
  {
    name: "SAVED_VIEW_KINDS",
    type: "SavedViewKind",
    values: rawSavedViewKindEnum,
  },
  {
    name: "ACTIVITY_ACTIONS",
    type: "ActivityAction",
    values: rawActivityActionEnum,
  },
  { name: "JOB_KINDS", type: "JobKind", values: rawJobKindEnum },
  { name: "JOB_STATUSES", type: "JobStatus", values: rawJobStatusEnum },
  {
    name: "AUDIO_EXTENSIONS",
    type: "AudioExtension",
    values: AUDIO_EXTENSIONS,
  },
  { name: "MEASURE_NAMES", type: "MeasureName", values: MEASURE_NAMES },
  {
    name: "DAW_CAPABILITIES",
    type: "DawCapability",
    values: DAW_CAPABILITIES,
  },
  { name: "SAMPLE_KINDS", type: "SampleKind", values: SAMPLE_KINDS },
  { name: "SAMPLE_STATUSES", type: "SampleStatus", values: SAMPLE_STATUSES },
];

/**
 * Each paginated listing's column filters, read off the module that declares
 * them (`EntityList.filterParams`, built from the listing's filter schema):
 * the client's filter vocabulary, so a filter the server reads cannot be
 * missing from it. One `<KIND>_FILTER_PARAMS` per listed kind, emitted after
 * the value lists.
 */
export const FILTER_PARAMS: {
  name: string;
  type: string;
  values: readonly string[];
}[] = entityModules().flatMap((module) =>
  module.list
    ? [
        {
          name: `${module.kind.toUpperCase()}_FILTER_PARAMS`,
          type: `${module.label}FilterParam`,
          values: module.list.filterParams,
        },
      ]
    : []
);

/**
 * The OpenAPI document, built in process. `/api/openapi` is registered ahead
 * of the session middleware and Drizzle opens no connection until a query
 * runs, so this needs neither a port nor a database.
 */
export async function buildOpenApiDocument(): Promise<Record<string, unknown>> {
  const response = await app.request("/api/openapi");
  if (!response.ok) {
    throw new Error(
      `GET /api/openapi returned ${response.status} ${response.statusText}`
    );
  }
  return (await response.json()) as Record<string, unknown>;
}

export function buildEnumsSource(): string {
  const blocks = [...ENUMS, ...FILTER_PARAMS].map(
    ({ name, type, values }) =>
      `export const ${name} = [\n${values
        .map((value) => `  ${JSON.stringify(value)},`)
        .join(
          "\n"
        )}\n] as const;\n\nexport type ${type} = (typeof ${name})[number];`
  );
  return [HEADER, ...blocks].join("\n\n") + "\n";
}

async function renderApiTypes(
  document: Record<string, unknown>
): Promise<string> {
  const scratch = await mkdtemp(join(tmpdir(), "projammr-openapi-"));
  try {
    const specPath = join(scratch, "openapi.json");
    await writeFile(specPath, JSON.stringify(document));
    const { stdout } = await run("bunx", [OPENAPI_TYPESCRIPT, specPath], {
      maxBuffer: 32 * 1024 * 1024,
    });
    return stdout;
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

async function writeFormatted(filePath: string, source: string): Promise<void> {
  const config = await resolveConfig(filePath);
  await writeFile(
    filePath,
    await format(source, { ...config, filepath: filePath })
  );
  console.log(`wrote ${filePath}`);
}

export async function generate(): Promise<void> {
  const document = await buildOpenApiDocument();
  await writeFormatted(
    resolve(API_SRC, "v1.d.ts"),
    `${HEADER}\n${await renderApiTypes(document)}`
  );
  await writeFormatted(resolve(API_SRC, "enums.ts"), buildEnumsSource());
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await generate();
}
