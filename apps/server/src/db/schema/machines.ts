import { sql } from "drizzle-orm";
import {
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  varchar,
} from "drizzle-orm/pg-core";
import { z } from "zod";
import { authSessions, publicUserSchema, users } from "./auth.js";
import { baseTimestamps } from "./base.js";
import { sessions } from "./sessions.js";

const MACHINE_NAME_MAX_LENGTH = 64;

/**
 * How long a machine's last beat stays fresh. Past it the machine reads as
 * offline and its open session no longer counts as open.
 */
export const MACHINE_OFFLINE_AFTER_MS = 90_000;

/**
 * The id a machine generates for itself once and sends as the id in
 * `PUT /machines/:id` and as `X-Machine-Id` on every dit request. It names a
 * machine and grants nothing: every route checks the row's owner against the
 * session.
 */
export const deviceIdSchema = z
  .string()
  .regex(/^[A-Za-z0-9_-]{16,64}$/, "A device id is 16-64 of A-Z a-z 0-9 _ -");

/**
 * A machine running the dit app, as its owner's beats describe it. `id` is
 * generated by the app and kept across launches; a machine belongs to the
 * account that first beat it, and every other account is refused its id.
 *
 * Removing a machine sets `removedAt` rather than deleting the row, so the
 * saves, commits and segments that name it keep a valid reference and its last
 * name; a removed machine is read nowhere and its name is free to reuse.
 * `authSessionId` is the sign-in its last beat came from, which a removal
 * revokes.
 *
 * `openSessionId` is the session the machine has open, kept only while its
 * owner is a member of that session's project. `repoIds` are the repos the
 * machine's dit sets live in, so a session's presence can say whether the
 * machine tracks its repo.
 */
export const machines = pgTable(
  "machines",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .references(() => users.id, { onDelete: "cascade" })
      .notNull(),
    name: varchar("name", { length: MACHINE_NAME_MAX_LENGTH }).notNull(),
    platform: varchar("platform", { length: 64 }).notNull(),
    appVersion: varchar("app_version", { length: 64 }).notNull(),
    lastSeenAt: timestamp("last_seen_at").notNull(),
    openSessionId: integer("open_session_id").references(() => sessions.id, {
      onDelete: "set null",
    }),
    repoIds: integer("repo_ids").array().notNull().default([]),
    removedAt: timestamp("removed_at"),
    authSessionId: text("auth_session_id").references(() => authSessions.id, {
      onDelete: "set null",
    }),
    ...baseTimestamps,
  },
  (t) => [
    uniqueIndex("machines_user_name")
      .on(t.userId, t.name)
      .where(sql`${t.removedAt} is null`),
    index("machines_user").on(t.userId),
    index("machines_open_session").on(t.openSessionId),
  ]
);

/** A machine as its owner reads it. `online` is derived from `lastSeenAt`. */
export const machineSchema = z.object({
  id: z.string(),
  name: z.string(),
  platform: z.string(),
  appVersion: z.string(),
  lastSeenAt: z.date(),
  online: z.boolean(),
  openSessionId: z.number().int().nullable(),
});
export type MachineView = z.infer<typeof machineSchema>;

/** A repo a machine has pushed to, as its owner may read it. */
export const pushedRepoSchema = z.object({
  id: z.number().int(),
  name: z.string(),
  projectId: z.number().int(),
});
export type PushedRepo = z.infer<typeof pushedRepoSchema>;

/** A session a machine currently has open, as its owner may read it. */
export const openSessionSchema = z.object({
  id: z.number().int(),
  name: z.string(),
  projectId: z.number().int(),
});

/**
 * One of the caller's machines: the repos it tracks (`repoIds`, as its beats
 * report them), the set it has open, the repos it has pushed to and the
 * folders its owner told dit never to look for renders in.
 */
export const machineListItemSchema = machineSchema.extend({
  repoIds: z.array(z.number().int()),
  openSession: openSessionSchema.nullable(),
  pushedRepos: z.array(pushedRepoSchema),
  neverHere: z.array(z.object({ id: z.number().int(), folder: z.string() })),
});

/** A machine on the instance's list, with the account it belongs to. */
const adminMachineSchema = z.object({
  id: z.string(),
  name: z.string(),
  platform: z.string(),
  appVersion: z.string(),
  lastSeenAt: z.date(),
  owner: publicUserSchema.pick({ id: true, name: true }),
});

/** One page of every account's machines, and how many there are in all. */
export const adminMachinesSchema = z.object({
  items: z.array(adminMachineSchema),
  total: z.number().int(),
});

/**
 * A machine's name as the hub keeps it: trimmed, then cut to the longest
 * prefix of whole characters that is at most 64 UTF-16 code units, so a pair
 * of surrogates (an emoji) is never split. A longer name is cut rather than
 * refused, as a device name is. dit cuts a name the same way before sending.
 */
function cutMachineName(name: string): string {
  const trimmed = name.trim();
  if (trimmed.length <= MACHINE_NAME_MAX_LENGTH) return trimmed;
  const last = trimmed.charCodeAt(MACHINE_NAME_MAX_LENGTH - 1);
  const next = trimmed.charCodeAt(MACHINE_NAME_MAX_LENGTH);
  const splitsPair =
    last >= 0xd800 && last <= 0xdbff && next >= 0xdc00 && next <= 0xdfff;
  return trimmed.slice(0, MACHINE_NAME_MAX_LENGTH - (splitsPair ? 1 : 0));
}

/** A machine name in a request body: non-empty once trimmed, cut by {@link cutMachineName}. */
export const machineNameSchema = z
  .string()
  .trim()
  .min(1)
  .transform(cutMachineName);

/**
 * The machine name a pushed row carries: cut and trimmed as a beat's is, so it
 * compares equal to the name the hub holds for the machine; null when the row
 * names none.
 */
export const pushedMachineNameSchema = z
  .string()
  .transform(cutMachineName)
  .nullable();

/** A beat: who the machine is and what it has open. */
export const machineBeatSchema = z.object({
  name: machineNameSchema,
  platform: z.string().trim().min(1).max(64),
  appVersion: z.string().trim().min(1).max(64),
  openSessionId: z.number().int().positive().nullable(),
  repoIds: z
    .array(z.number().int().positive())
    .max(500)
    .transform((ids) => [...new Set(ids)]),
});
export type MachineBeat = z.infer<typeof machineBeatSchema>;

/** One of the caller's machines online on a session, and how it relates to it. */
export const sessionPresenceSchema = z.object({
  machines: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      tracksRepo: z.boolean(),
      openingThis: z.boolean(),
    })
  ),
});

/**
 * The machine owned by a project member that has this session open, as the
 * session page reads it. Null when no such machine is online.
 */
export const openOnSchema = z
  .object({
    machine: z.string(),
    owner: publicUserSchema.pick({ id: true, name: true }),
  })
  .nullable();
export type OpenOn = z.infer<typeof openOnSchema>;
