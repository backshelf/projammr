/**
 * Single-use record for `private_key_jwt` client assertion `jti` values. The
 * row id is a digest of the per-client assertion identifier, so a replayed
 * or concurrent assertion collides on the primary key and the insert fails
 * atomically. A row blocks its id until `expiresAt` makes removal safe.
 */
export const oauthClientAssertions = pgTable("oauth_client_assertions", {
  id: text("id").primaryKey(),
  expiresAt: timestamp("expires_at").notNull(),
});

/**
 * The JWT plugin's signing-key table. The adapter looks this model up as
 * `jwkss` (`${model}s` under `usePlural: true`), so `auth.ts` aliases
 * `jwkss: jwks` rather than this table being named `jwkss`.
 */
export const jwks = pgTable("jwks", {
  id: text("id").primaryKey(),
  publicKey: text("public_key").notNull(),
  privateKey: text("private_key").notNull(),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  expiresAt: timestamp("expires_at"),
  alg: text("alg"),
  crv: text("crv"),
});
